"""
Asset Optimizer & Code Generator for Figma SVGs (v2.1 Standard)
Pure Python SVGO-style vector optimizer, currentColor transformer,
and React / TypeScript icon index barrel generator.
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

# Register default SVG namespace to prevent 'ns0:' prefix
ET.register_namespace('', "http://www.w3.org/2000/svg")

def round_floats_in_path(path_str, precision=2):
    """Rounds verbose floating-point numbers in SVG path 'd' attributes."""
    def repl(match):
        val = float(match.group(0))
        if val.is_integer():
            return str(int(val))
        return f"{val:.{precision}f}".rstrip('0').rstrip('.')
    return re.sub(r'-?\d+\.\d+', repl, path_str)

def get_descendants(element):
    """Recursively returns all descendants of an XML element."""
    desc = set()
    for child in element:
        desc.add(child)
        desc.update(get_descendants(child))
    return desc

def optimize_svg(svg_content, use_current_color=False, round_precision=2):
    """
    Optimizes raw Figma SVG content:
    - Strips bloated floating-point precision in coordinates
    - Removes redundant metadata, comments, and empty groups
    - Replaces single-tone monochrome colors with 'currentColor' for Tailwind/CSS color inheritance
    """
    # 1. Strip XML declaration & comments
    svg_content = re.sub(r'<\?xml.*?\?>', '', svg_content, flags=re.DOTALL)
    svg_content = re.sub(r'<!--.*?-->', '', svg_content, flags=re.DOTALL)

    try:
        root = ET.fromstring(svg_content.strip())
    except Exception:
        return svg_content.strip()

    # Find elements inside defs/clipPath/mask to ignore their fills
    ignored_elements = set()
    for elem in root.iter():
        tag = elem.tag.split('}')[-1]
        if tag in ('defs', 'clipPath', 'mask'):
            ignored_elements.add(elem)
            ignored_elements.update(get_descendants(elem))

    # 2. Detect visible content colors
    colors = set()
    for elem in root.iter():
        if elem in ignored_elements:
            continue
        for attr in ('stroke', 'fill'):
            val = elem.attrib.get(attr)
            if val and val.lower() not in ('none', 'transparent', 'inherit', 'currentcolor'):
                colors.add(val.upper())

    # Monochrome check (at most 1 active visible color tone)
    is_monochrome = (len(colors) <= 1)

    # 3. Clean and transform elements
    for elem in root.iter():
        elem.attrib.pop('id', None)
        elem.attrib.pop('clip-rule', None)
        elem.attrib.pop('fill-rule', None)

        if elem in ignored_elements:
            continue

        # Optimize 'd' paths
        if 'd' in elem.attrib:
            elem.attrib['d'] = round_floats_in_path(elem.attrib['d'], precision=round_precision)

        # Convert to currentColor if monochrome and enabled
        if use_current_color and is_monochrome:
            if elem.attrib.get('stroke') and elem.attrib['stroke'].lower() not in ('none', 'transparent'):
                elem.attrib['stroke'] = 'currentColor'
            if elem.attrib.get('fill') and elem.attrib['fill'].lower() not in ('none', 'transparent'):
                elem.attrib['fill'] = 'currentColor'

    # Remove empty groups
    for parent in root.iter():
        for child in list(parent):
            tag = child.tag.split('}')[-1]
            if tag == 'g' and len(child) == 0 and not child.text:
                parent.remove(child)

    out = ET.tostring(root, encoding='utf-8').decode('utf-8')
    out = re.sub(r'>\s+<', '><', out).strip()
    return out

def optimize_svg_file(input_path, output_path=None, use_current_color=False):
    """Reads, optimizes, and writes an SVG file."""
    if output_path is None:
        output_path = input_path

    with open(input_path, 'r', encoding='utf-8') as f:
        content = f.read()

    optimized = optimize_svg(content, use_current_color=use_current_color)

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(optimized)

    orig_size = len(content.encode('utf-8'))
    new_size = len(optimized.encode('utf-8'))
    reduction = (orig_size - new_size) / orig_size * 100 if orig_size > 0 else 0
    return orig_size, new_size, reduction

def generate_icon_barrel(icons_dir, output_ts_path=None):
    """
    Generates a TypeScript/React barrel file (index.ts) from all SVGs in a folder.
    Creates clean PascalCase identifiers from slugged icon names.
    """
    if output_ts_path is None:
        output_ts_path = os.path.join(icons_dir, 'index.ts')

    svg_files = sorted([f for f in os.listdir(icons_dir) if f.endswith('.svg')])
    if not svg_files:
        return 0

    lines = [
        "// Auto-generated by figma-standard-ui v2.1 Asset Optimizer",
        "// Do not edit manually.",
        ""
    ]

    for fname in svg_files:
        slug = os.path.splitext(fname)[0]
        clean_name = re.sub(r'^\d+[-_]?', '', slug)
        pascal = "".join(part.capitalize() for part in re.split(r'[-_]', clean_name) if part)
        component_name = f"Icon{pascal}"
        lines.append(f"export {{ default as {component_name} }} from './{fname}';")

    lines.append("")
    with open(output_ts_path, 'w', encoding='utf-8') as f:
        f.write("\n".join(lines))

    return len(svg_files)

def process_directory(target_dir, use_current_color=False, make_barrel=True):
    """Processes all SVG icons in target_dir or recursively in all 02-icon folders."""
    total_files = 0
    total_saved_bytes = 0

    for root, dirs, files in os.walk(target_dir):
        if os.path.basename(root) in ('02-icon', '06-vector'):
            svgs = [f for f in files if f.endswith('.svg')]
            for s in svgs:
                fpath = os.path.join(root, s)
                orig, new, red = optimize_svg_file(fpath, use_current_color=use_current_color)
                total_files += 1
                total_saved_bytes += (orig - new)
            if make_barrel and svgs and os.path.basename(root) == '02-icon':
                generate_icon_barrel(root)

    print(f"[OK] Optimized {total_files} SVGs.")
    print(f"[OK] Total bytes saved: {total_saved_bytes:,} bytes.")

if __name__ == '__main__':
    if len(sys.argv) < 2:
        print("Usage: python asset_optimizer.py <directory_or_file> [--current-color] [--no-barrel]")
        sys.exit(1)

    target = sys.argv[1]
    curr_color = '--current-color' in sys.argv
    no_barrel = '--no-barrel' in sys.argv

    if os.path.isfile(target) and target.endswith('.svg'):
        orig, new, red = optimize_svg_file(target, use_current_color=curr_color)
        print(f"Optimized {os.path.basename(target)}: {orig} -> {new} bytes ({red:.1f}% reduction)")
    elif os.path.isdir(target):
        process_directory(target, use_current_color=curr_color, make_barrel=not no_barrel)
